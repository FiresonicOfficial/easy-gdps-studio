-- EasyGDPS Studio SQLite Schema
-- Clean, empty initial database for Geometry Dash Private Servers (1.0 - 2.2)

PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS server_meta (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS accounts (
  accountID INTEGER PRIMARY KEY AUTOINCREMENT,
  userName TEXT NOT NULL COLLATE NOCASE UNIQUE,
  passwordHash TEXT NOT NULL,
  gjp2Hash TEXT NOT NULL DEFAULT '',
  email TEXT NOT NULL DEFAULT '',
  secret TEXT NOT NULL DEFAULT '',
  saveData TEXT NOT NULL DEFAULT '',
  isActive INTEGER NOT NULL DEFAULT 1,
  isAdmin INTEGER NOT NULL DEFAULT 0,
  mS INTEGER NOT NULL DEFAULT 0,
  frS INTEGER NOT NULL DEFAULT 0,
  cS INTEGER NOT NULL DEFAULT 0,
  youtubeurl TEXT NOT NULL DEFAULT '',
  twitter TEXT NOT NULL DEFAULT '',
  twitch TEXT NOT NULL DEFAULT '',
  discord TEXT NOT NULL DEFAULT '',
  registerDate INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS users (
  userID INTEGER PRIMARY KEY AUTOINCREMENT,
  accountID INTEGER NOT NULL DEFAULT 0,
  extID TEXT NOT NULL DEFAULT '',
  udid TEXT NOT NULL DEFAULT '',
  userName TEXT NOT NULL DEFAULT 'Player',
  stars INTEGER NOT NULL DEFAULT 0,
  moons INTEGER NOT NULL DEFAULT 0,
  demons INTEGER NOT NULL DEFAULT 0,
  diamonds INTEGER NOT NULL DEFAULT 0,
  coins INTEGER NOT NULL DEFAULT 0,
  userCoins INTEGER NOT NULL DEFAULT 0,
  creatorPoints INTEGER NOT NULL DEFAULT 0,
  icon INTEGER NOT NULL DEFAULT 1,
  color1 INTEGER NOT NULL DEFAULT 0,
  color2 INTEGER NOT NULL DEFAULT 3,
  color3 INTEGER NOT NULL DEFAULT 0,
  iconType INTEGER NOT NULL DEFAULT 0,
  special INTEGER NOT NULL DEFAULT 0,
  accIcon INTEGER NOT NULL DEFAULT 1,
  accShip INTEGER NOT NULL DEFAULT 1,
  accBall INTEGER NOT NULL DEFAULT 1,
  accBird INTEGER NOT NULL DEFAULT 1,
  accDart INTEGER NOT NULL DEFAULT 1,
  accRobot INTEGER NOT NULL DEFAULT 1,
  accGlow INTEGER NOT NULL DEFAULT 0,
  accSpider INTEGER NOT NULL DEFAULT 1,
  accExplosion INTEGER NOT NULL DEFAULT 1,
  accSwing INTEGER NOT NULL DEFAULT 1,
  accJetpack INTEGER NOT NULL DEFAULT 1,
  demonInfo TEXT NOT NULL DEFAULT '',
  classicLevelsCompleted TEXT NOT NULL DEFAULT '',
  platformerLevelsCompleted TEXT NOT NULL DEFAULT '',
  isMod INTEGER NOT NULL DEFAULT 0,
  modBadge INTEGER NOT NULL DEFAULT 0,
  isBanned INTEGER NOT NULL DEFAULT 0,
  isCreatorBanned INTEGER NOT NULL DEFAULT 0,
  lastPlayed INTEGER NOT NULL DEFAULT 0,
  ip TEXT NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS idx_users_accountID ON users (accountID);
CREATE INDEX IF NOT EXISTS idx_users_extID ON users (extID);
CREATE INDEX IF NOT EXISTS idx_users_udid ON users (udid);
CREATE INDEX IF NOT EXISTS idx_users_stars ON users (stars DESC);
CREATE INDEX IF NOT EXISTS idx_users_cp ON users (creatorPoints DESC);

CREATE TABLE IF NOT EXISTS levels (
  levelID INTEGER PRIMARY KEY AUTOINCREMENT,
  extID TEXT NOT NULL DEFAULT '',
  userID INTEGER NOT NULL DEFAULT 0,
  userName TEXT NOT NULL DEFAULT 'Player',
  levelName TEXT NOT NULL DEFAULT 'Unnamed',
  levelDesc TEXT NOT NULL DEFAULT '',
  levelVersion INTEGER NOT NULL DEFAULT 1,
  levelLength INTEGER NOT NULL DEFAULT 0,
  audioTrack INTEGER NOT NULL DEFAULT 0,
  auto INTEGER NOT NULL DEFAULT 0,
  password TEXT NOT NULL DEFAULT '0',
  original INTEGER NOT NULL DEFAULT 0,
  twoPlayer INTEGER NOT NULL DEFAULT 0,
  songID INTEGER NOT NULL DEFAULT 0,
  songIDs TEXT NOT NULL DEFAULT '',
  sfxIDs TEXT NOT NULL DEFAULT '',
  objects INTEGER NOT NULL DEFAULT 0,
  coins INTEGER NOT NULL DEFAULT 0,
  requestedStars INTEGER NOT NULL DEFAULT 0,
  extraString TEXT NOT NULL DEFAULT '',
  levelInfo TEXT NOT NULL DEFAULT '',
  secret TEXT NOT NULL DEFAULT '',
  gameVersion INTEGER NOT NULL DEFAULT 21,
  binaryVersion INTEGER NOT NULL DEFAULT 35,
  ldm INTEGER NOT NULL DEFAULT 0,
  wt INTEGER NOT NULL DEFAULT 0,
  wt2 INTEGER NOT NULL DEFAULT 0,
  ts INTEGER NOT NULL DEFAULT 0,
  unlisted INTEGER NOT NULL DEFAULT 0,
  unlisted2 INTEGER NOT NULL DEFAULT 0,
  friendsOnly INTEGER NOT NULL DEFAULT 0,
  starDifficulty INTEGER NOT NULL DEFAULT 0,
  starDemonDiff INTEGER NOT NULL DEFAULT 0,
  starStars INTEGER NOT NULL DEFAULT 0,
  starCoins INTEGER NOT NULL DEFAULT 0,
  starFeatured INTEGER NOT NULL DEFAULT 0,
  starEpic INTEGER NOT NULL DEFAULT 0,
  starDemon INTEGER NOT NULL DEFAULT 0,
  starAuto INTEGER NOT NULL DEFAULT 0,
  starHall INTEGER NOT NULL DEFAULT 0,
  rateDate INTEGER NOT NULL DEFAULT 0,
  downloads INTEGER NOT NULL DEFAULT 0,
  likes INTEGER NOT NULL DEFAULT 0,
  dislikes INTEGER NOT NULL DEFAULT 0,
  isDeleted INTEGER NOT NULL DEFAULT 0,
  uploadDate INTEGER NOT NULL DEFAULT 0,
  updateDate INTEGER NOT NULL DEFAULT 0,
  hostname TEXT NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS idx_levels_userID ON levels (userID);
CREATE INDEX IF NOT EXISTS idx_levels_downloads ON levels (downloads DESC);
CREATE INDEX IF NOT EXISTS idx_levels_likes ON levels (likes DESC);
CREATE INDEX IF NOT EXISTS idx_levels_stars ON levels (starStars DESC);
CREATE INDEX IF NOT EXISTS idx_levels_featured ON levels (starFeatured DESC);
CREATE INDEX IF NOT EXISTS idx_levels_uploadDate ON levels (uploadDate DESC);

CREATE TABLE IF NOT EXISTS comments (
  commentID INTEGER PRIMARY KEY AUTOINCREMENT,
  userID INTEGER NOT NULL DEFAULT 0,
  userName TEXT NOT NULL DEFAULT 'Player',
  levelID INTEGER NOT NULL DEFAULT 0,
  comment TEXT NOT NULL DEFAULT '',
  percent INTEGER NOT NULL DEFAULT 0,
  likes INTEGER NOT NULL DEFAULT 0,
  isSpam INTEGER NOT NULL DEFAULT 0,
  timestamp INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_comments_levelID ON comments (levelID, commentID DESC);
CREATE INDEX IF NOT EXISTS idx_comments_userID ON comments (userID, commentID DESC);

CREATE TABLE IF NOT EXISTS account_comments (
  commentID INTEGER PRIMARY KEY AUTOINCREMENT,
  accountID INTEGER NOT NULL DEFAULT 0,
  userID INTEGER NOT NULL DEFAULT 0,
  comment TEXT NOT NULL DEFAULT '',
  likes INTEGER NOT NULL DEFAULT 0,
  isSpam INTEGER NOT NULL DEFAULT 0,
  timestamp INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_acc_comments_accountID ON account_comments (accountID, commentID DESC);

CREATE TABLE IF NOT EXISTS scores (
  scoreID INTEGER PRIMARY KEY AUTOINCREMENT,
  accountID INTEGER NOT NULL DEFAULT 0,
  userID INTEGER NOT NULL DEFAULT 0,
  levelID INTEGER NOT NULL DEFAULT 0,
  percent INTEGER NOT NULL DEFAULT 0,
  attempts INTEGER NOT NULL DEFAULT 0,
  coins INTEGER NOT NULL DEFAULT 0,
  clicks INTEGER NOT NULL DEFAULT 0,
  timeMs INTEGER NOT NULL DEFAULT 0,
  stars INTEGER NOT NULL DEFAULT 0,
  demons INTEGER NOT NULL DEFAULT 0,
  diamonds INTEGER NOT NULL DEFAULT 0,
  moons INTEGER NOT NULL DEFAULT 0,
  uploadDate INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_scores_userID ON scores (userID);
CREATE INDEX IF NOT EXISTS idx_scores_levelID ON scores (levelID);

CREATE TABLE IF NOT EXISTS songs (
  ID INTEGER PRIMARY KEY,
  name TEXT NOT NULL DEFAULT 'Unknown Song',
  authorID INTEGER NOT NULL DEFAULT 0,
  authorName TEXT NOT NULL DEFAULT 'Unknown Artist',
  size REAL NOT NULL DEFAULT 0,
  download TEXT NOT NULL DEFAULT '',
  hash TEXT NOT NULL DEFAULT '',
  isDisabled INTEGER NOT NULL DEFAULT 0,
  levelsCount INTEGER NOT NULL DEFAULT 0,
  reuploadTime INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS level_lists (
  listID INTEGER PRIMARY KEY AUTOINCREMENT,
  listName TEXT NOT NULL DEFAULT '',
  listDesc TEXT NOT NULL DEFAULT '',
  listVersion INTEGER NOT NULL DEFAULT 1,
  accountID INTEGER NOT NULL DEFAULT 0,
  userName TEXT NOT NULL DEFAULT 'Player',
  listLevels TEXT NOT NULL DEFAULT '',
  starDifficulty INTEGER NOT NULL DEFAULT -1,
  starFeatured INTEGER NOT NULL DEFAULT 0,
  countForReward INTEGER NOT NULL DEFAULT 0,
  starReward INTEGER NOT NULL DEFAULT 0,
  downloads INTEGER NOT NULL DEFAULT 0,
  likes INTEGER NOT NULL DEFAULT 0,
  unlisted INTEGER NOT NULL DEFAULT 0,
  uploadDate INTEGER NOT NULL DEFAULT 0,
  updateDate INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS daily_features (
  feaID INTEGER PRIMARY KEY AUTOINCREMENT,
  levelID INTEGER NOT NULL,
  timestamp INTEGER NOT NULL DEFAULT 0,
  type INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_daily_type_ts ON daily_features (type, timestamp DESC);

CREATE TABLE IF NOT EXISTS likes (
  likeID INTEGER PRIMARY KEY AUTOINCREMENT,
  itemID INTEGER NOT NULL,
  type INTEGER NOT NULL DEFAULT 1,
  likeValue INTEGER NOT NULL DEFAULT 1,
  accountID INTEGER NOT NULL DEFAULT 0,
  userID INTEGER NOT NULL DEFAULT 0,
  ip TEXT NOT NULL DEFAULT '',
  timestamp INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_likes_lookup ON likes (itemID, type, accountID, ip);

CREATE TABLE IF NOT EXISTS rate_suggestions (
  suggestionID INTEGER PRIMARY KEY AUTOINCREMENT,
  levelID INTEGER NOT NULL,
  accountID INTEGER NOT NULL DEFAULT 0,
  userID INTEGER NOT NULL DEFAULT 0,
  suggestStars INTEGER NOT NULL DEFAULT 0,
  suggestFeatured INTEGER NOT NULL DEFAULT 0,
  suggestDifficulty INTEGER NOT NULL DEFAULT 0,
  timestamp INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_rate_suggestions_level ON rate_suggestions (levelID);

CREATE TABLE IF NOT EXISTS gauntlets (
  ID INTEGER PRIMARY KEY,
  level1 INTEGER NOT NULL DEFAULT 0,
  level2 INTEGER NOT NULL DEFAULT 0,
  level3 INTEGER NOT NULL DEFAULT 0,
  level4 INTEGER NOT NULL DEFAULT 0,
  level5 INTEGER NOT NULL DEFAULT 0,
  timestamp INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS mappacks (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL DEFAULT '',
  levels TEXT NOT NULL DEFAULT '',
  stars INTEGER NOT NULL DEFAULT 0,
  coins INTEGER NOT NULL DEFAULT 0,
  difficulty INTEGER NOT NULL DEFAULT 0,
  rgbcolors TEXT NOT NULL DEFAULT '255,255,255',
  colors2 TEXT NOT NULL DEFAULT 'none'
);
